package com.scrapestudio.project;

import com.scrapestudio.project.dto.FieldDto;
import com.scrapestudio.project.dto.ProjectDetail;
import org.springframework.stereotype.Service;

import java.util.List;
import java.util.Locale;

@Service
public class CodeGenerator {

    public String generate(ProjectDetail project, String language) {
        String normalized = language == null ? "python" : language.trim().toLowerCase(Locale.ROOT);
        return switch (normalized) {
            case "python" -> python(project);
            case "java" -> javaCode(project);
            case "node", "javascript", "js" -> node(project);
            default -> throw new IllegalArgumentException("Unsupported language: " + language);
        };
    }

    private String python(ProjectDetail project) {
        List<FieldDto> fields = project.fields();
        if (fields.isEmpty()) {
            return """
                    # Generated by ScrapeStudio
                    # Add at least one field in the visual builder first.
                    """;
        }

        boolean needsPlaywright = requiresPlaywright(project);
        return needsPlaywright ? pythonPlaywright(project) : pythonRequests(project);
    }

    private boolean requiresPlaywright(ProjectDetail project) {
        if ("XPATH".equalsIgnoreCase(project.itemSelectorType())) {
            return true;
        }
        return project.fields().stream()
                .anyMatch(field -> "XPATH".equalsIgnoreCase(field.selectorType()));
    }

    private String pythonRequests(ProjectDetail project) {
        StringBuilder code = new StringBuilder();
        code.append("""
                # Generated by ScrapeStudio
                # Respect robots.txt and the target site's terms of service.
                import requests
                from bs4 import BeautifulSoup

                """);
        code.append("URL = ").append(pyString(project.url())).append("\n");
        code.append("HEADERS = {\n");
        code.append("    \"User-Agent\": \"Mozilla/5.0 (compatible; ScrapeStudio/0.1; +https://github.com/xiangbiaoqiao/scrape-studio)\",\n");
        code.append("    \"Accept-Language\": \"en-US,en;q=0.9\",\n");
        code.append("}\n\n");
        code.append("response = requests.get(URL, headers=HEADERS, timeout=30)\n");
        code.append("response.raise_for_status()\n");
        code.append("soup = BeautifulSoup(response.text, \"html.parser\")\n\n");

        if (hasText(project.itemSelector())) {
            code.append("ITEM_SELECTOR = ").append(pyString(project.itemSelector())).append("\n\n");
            code.append("rows = []\n");
            code.append("for item in soup.select(ITEM_SELECTOR):\n");
            code.append("    rows.append({\n");
            for (FieldDto field : project.fields()) {
                code.append("        ").append(pyString(field.name())).append(": ")
                        .append(pyValue(field, "item")).append(",\n");
            }
            code.append("    })\n\n");
        } else {
            code.append("row = {\n");
            for (FieldDto field : project.fields()) {
                code.append("    ").append(pyString(field.name())).append(": ")
                        .append(pyValue(field, "soup")).append(",\n");
            }
            code.append("}\n");
            code.append("rows = [row]\n\n");
        }

        code.append("print(f\"Extracted {len(rows)} row(s)\")\n");
        code.append("print(rows[:5])\n");
        return code.toString();
    }

    private String pythonPlaywright(ProjectDetail project) {
        StringBuilder code = new StringBuilder();
        code.append("""
                # Generated by ScrapeStudio
                # Respect robots.txt and the target site's terms of service.
                # Requires: pip install playwright && playwright install chromium
                from playwright.sync_api import sync_playwright

                """);
        code.append("URL = ").append(pyString(project.url())).append("\n");
        code.append("ITEM_SELECTOR = ").append(pyString(
                hasText(project.itemSelector()) ? withPrefix(project.itemSelector(), project.itemSelectorType()) : null
        )).append("\n\n");
        code.append("with sync_playwright() as p:\n");
        code.append("    browser = p.chromium.launch(headless=True)\n");
        code.append("    page = browser.new_page()\n");
        code.append("    page.goto(URL, wait_until=\"domcontentloaded\", timeout=60_000)\n\n");
        code.append("    rows = []\n");
        if (hasText(project.itemSelector())) {
            code.append("    items = page.locator(ITEM_SELECTOR)\n");
            code.append("    for index in range(items.count()):\n");
            code.append("        item = items.nth(index)\n");
            code.append("        rows.append({\n");
            for (FieldDto field : project.fields()) {
                code.append("            ").append(pyString(field.name())).append(": ")
                        .append(pyPlaywrightValue(field, "item")).append(",\n");
            }
            code.append("        })\n\n");
        } else {
            code.append("    rows.append({\n");
            for (FieldDto field : project.fields()) {
                code.append("        ").append(pyString(field.name())).append(": ")
                        .append(pyPlaywrightValue(field, "page")).append(",\n");
            }
            code.append("    })\n\n");
        }
        code.append("    browser.close()\n\n");
        code.append("print(f\"Extracted {len(rows)} row(s)\")\n");
        code.append("print(rows[:5])\n");
        return code.toString();
    }

    private String javaCode(ProjectDetail project) {
        List<FieldDto> fields = project.fields();
        if (fields.isEmpty()) {
            return """
                    // Generated by ScrapeStudio
                    // Add at least one field in the visual builder first.
                    """;
        }

        StringBuilder code = new StringBuilder();
        code.append("""
                // Generated by ScrapeStudio
                // Respect robots.txt and the target site's terms of service.
                // Requires: org.jsoup:jsoup:1.18.1
                import org.jsoup.Jsoup;
                import org.jsoup.nodes.Document;
                import org.jsoup.nodes.Element;
                import org.jsoup.select.Elements;

                import java.util.ArrayList;
                import java.util.LinkedHashMap;
                import java.util.List;
                import java.util.Map;

                public class ScrapeResult {
                    public static void main(String[] args) throws Exception {
                """);
        code.append("        String url = ").append(javaString(project.url())).append(";\n");
        code.append("        Document doc = Jsoup.connect(url)\n");
        code.append("                .userAgent(\"Mozilla/5.0 (compatible; ScrapeStudio/0.1)\")\n");
        code.append("                .timeout(30_000)\n");
        code.append("                .get();\n\n");
        code.append("        List<Map<String, String>> rows = new ArrayList<>();\n");

        if (hasText(project.itemSelector())) {
            code.append("        Elements items = doc.select(")
                    .append(javaString(project.itemSelector())).append(");\n");
            code.append("        for (Element item : items) {\n");
            code.append("            Map<String, String> row = new LinkedHashMap<>();\n");
            for (FieldDto field : project.fields()) {
                code.append("            row.put(").append(javaString(field.name())).append(", ")
                        .append(javaValue(field, "item")).append(");\n");
            }
            code.append("            rows.add(row);\n");
            code.append("        }\n\n");
        } else {
            code.append("        Map<String, String> row = new LinkedHashMap<>();\n");
            for (FieldDto field : project.fields()) {
                code.append("        row.put(").append(javaString(field.name())).append(", ")
                        .append(javaValue(field, "doc")).append(");\n");
            }
            code.append("        rows.add(row);\n\n");
        }

        code.append("        System.out.println(\"Extracted \" + rows.size() + \" row(s)\");\n");
        code.append("        rows.stream().limit(5).forEach(System.out::println);\n");
        code.append("    }\n");
        code.append("}\n");
        return code.toString();
    }

    private String node(ProjectDetail project) {
        List<FieldDto> fields = project.fields();
        if (fields.isEmpty()) {
            return """
                    // Generated by ScrapeStudio
                    // Add at least one field in the visual builder first.
                    """;
        }

        StringBuilder code = new StringBuilder();
        code.append("""
                // Generated by ScrapeStudio
                // Respect robots.txt and the target site's terms of service.
                // Requires: npm install playwright && npx playwright install chromium
                import { chromium } from 'playwright';

                """);
        code.append("const URL = ").append(jsString(project.url())).append(";\n");
        code.append("const ITEM_SELECTOR = ").append(jsString(
                hasText(project.itemSelector()) ? withPrefix(project.itemSelector(), project.itemSelectorType()) : null
        )).append(";\n\n");
        code.append("const browser = await chromium.launch({ headless: true });\n");
        code.append("const page = await browser.newPage();\n");
        code.append("await page.goto(URL, { waitUntil: 'domcontentloaded', timeout: 60_000 });\n\n");
        code.append("const rows = [];\n");
        if (hasText(project.itemSelector())) {
            code.append("const items = page.locator(ITEM_SELECTOR);\n");
            code.append("const count = await items.count();\n");
            code.append("for (let index = 0; index < count; index++) {\n");
            code.append("  const item = items.nth(index);\n");
            code.append("  rows.push({\n");
            for (FieldDto field : project.fields()) {
                code.append("    ").append(jsString(field.name())).append(": ")
                        .append(jsValue(field, "item")).append(",\n");
            }
            code.append("  });\n");
            code.append("}\n\n");
        } else {
            code.append("rows.push({\n");
            for (FieldDto field : project.fields()) {
                code.append("  ").append(jsString(field.name())).append(": ")
                        .append(jsValue(field, "page")).append(",\n");
            }
            code.append("});\n\n");
        }
        code.append("await browser.close();\n\n");
        code.append("console.log(`Extracted ${rows.length} row(s)`);\n");
        code.append("console.log(rows.slice(0, 5));\n");
        return code.toString();
    }

    private String pyValue(FieldDto field, String root) {
        String selector = pyString(field.selector());
        if (field.multiple()) {
            if (isText(field)) {
                return "[" + "element.get_text(strip=True) for element in " + root + ".select(" + selector + ")]";
            }
            if (isHtml(field)) {
                return "[str(element) for element in " + root + ".select(" + selector + ")]";
            }
            return "[element.get(" + pyString(field.attribute()) + ") for element in "
                    + root + ".select(" + selector + ")]";
        }

        String element = root + ".select_one(" + selector + ")";
        if (isText(field)) {
            return element + ".get_text(strip=True) if " + element + " else \"\"";
        }
        if (isHtml(field)) {
            return "str(" + element + ") if " + element + " else \"\"";
        }
        return element + ".get(" + pyString(field.attribute()) + ") if " + element + " else \"\"";
    }

    private String pyPlaywrightValue(FieldDto field, String root) {
        String locator = root + ".locator(" + pyString(withPrefix(field.selector(), field.selectorType())) + ")";
        if (field.multiple()) {
            if (isText(field)) {
                return locator + ".all_inner_texts()";
            }
            if (isHtml(field)) {
                return locator + ".evaluate_all(\"els => els.map(el => el.innerHTML)\")";
            }
            return locator + ".evaluate_all(\"els => els.map(el => el.getAttribute('"
                    + escapeSingle(field.attribute()) + "'))\")";
        }

        String first = locator + ".first";
        if (isText(field)) {
            return first + ".inner_text().strip()";
        }
        if (isHtml(field)) {
            return first + ".inner_html()";
        }
        return first + ".get_attribute(" + pyString(field.attribute()) + ")";
    }

    private String javaValue(FieldDto field, String root) {
        String selector = javaString(field.selector());
        if (field.multiple()) {
            if (isText(field)) {
                return "String.join(\" | \", " + root + ".select(" + selector + ").eachText())";
            }
            if (isHtml(field)) {
                return "String.join(\" | \", " + root + ".select(" + selector
                        + ").stream().map(Element::outerHtml).toList())";
            }
            return "String.join(\" | \", " + root + ".select(" + selector + ").eachAttr("
                    + javaString(field.attribute()) + "))";
        }

        String element = root + ".selectFirst(" + selector + ")";
        String fallback = "\"\"";
        if (isText(field)) {
            return "(" + element + " != null ? " + element + ".text() : " + fallback + ")";
        }
        if (isHtml(field)) {
            return "(" + element + " != null ? " + element + ".outerHtml() : " + fallback + ")";
        }
        return "(" + element + " != null ? " + element + ".attr(" + javaString(field.attribute())
                + ") : " + fallback + ")";
    }

    private String jsValue(FieldDto field, String root) {
        String locator = root + ".locator(" + jsString(withPrefix(field.selector(), field.selectorType())) + ")";
        if (field.multiple()) {
            if (isText(field)) {
                return "await " + locator + ".allInnerTexts()";
            }
            if (isHtml(field)) {
                return "await " + locator + ".evaluateAll((els) => els.map((el) => el.innerHTML))";
            }
            return "await " + locator + ".evaluateAll((els) => els.map((el) => el.getAttribute("
                    + jsString(field.attribute()) + ")))";
        }

        String first = locator + ".first()";
        if (isText(field)) {
            return "(await " + first + ".innerText()).trim()";
        }
        if (isHtml(field)) {
            return "await " + first + ".innerHTML()";
        }
        return "await " + first + ".getAttribute(" + jsString(field.attribute()) + ")";
    }

    private boolean isText(FieldDto field) {
        return field.attribute() == null || field.attribute().isBlank()
                || "text".equalsIgnoreCase(field.attribute());
    }

    private boolean isHtml(FieldDto field) {
        return "html".equalsIgnoreCase(field.attribute());
    }

    private boolean hasText(String value) {
        return value != null && !value.isBlank();
    }

    private String withPrefix(String selector, String type) {
        if ("XPATH".equalsIgnoreCase(type)) {
            return "xpath=" + selector;
        }
        return selector;
    }

    private String pyString(String value) {
        if (value == null) {
            return "None";
        }
        return "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
    }

    private String escapeSingle(String value) {
        if (value == null) {
            return "";
        }
        return value.replace("\\", "\\\\").replace("'", "\\'");
    }

    private String javaString(String value) {
        if (value == null) {
            return "null";
        }
        return "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
    }

    private String jsString(String value) {
        if (value == null) {
            return "null";
        }
        return "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
    }
}
