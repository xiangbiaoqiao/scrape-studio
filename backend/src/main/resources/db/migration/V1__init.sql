CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'USER',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    url VARCHAR(2048) NOT NULL,
    description VARCHAR(1000),
    item_selector VARCHAR(1000),
    item_selector_type VARCHAR(20) NOT NULL DEFAULT 'CSS',
    schedule_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    interval_minutes INT NOT NULL DEFAULT 60,
    last_run_at TIMESTAMP WITH TIME ZONE,
    next_run_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_projects_owner ON projects (owner_id);
CREATE INDEX idx_projects_next_run ON projects (schedule_enabled, next_run_at);

CREATE TABLE fields (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    name VARCHAR(80) NOT NULL,
    selector VARCHAR(1000) NOT NULL,
    selector_type VARCHAR(20) NOT NULL DEFAULT 'CSS',
    attribute VARCHAR(80) NOT NULL DEFAULT 'text',
    multiple BOOLEAN NOT NULL DEFAULT FALSE,
    order_index INT NOT NULL DEFAULT 0
);

CREATE INDEX idx_fields_project ON fields (project_id);

CREATE TABLE runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    status VARCHAR(20) NOT NULL,
    trigger_type VARCHAR(20) NOT NULL DEFAULT 'MANUAL',
    started_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMP WITH TIME ZONE,
    duration_ms BIGINT,
    item_count INT NOT NULL DEFAULT 0,
    error_message VARCHAR(2000),
    result_json TEXT,
    diagnosis_json TEXT,
    screenshot_url VARCHAR(2048)
);

CREATE INDEX idx_runs_project ON runs (project_id);
CREATE INDEX idx_runs_started ON runs (started_at);
